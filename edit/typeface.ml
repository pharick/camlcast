(* Built once, and only if it is drawn: a game that hands {!Session.overlay} a
   font of its own never pays for this one. *)
let builtin =
  lazy
    (let atlas =
       Image.make ~width:(width * columns)
         ~height:(height * (Array.length cells / columns))
         (fun ~u ~v ->
           let cell = (v / height * columns) + (u / width) in
           let row = v mod height and column = u mod width in
           if cells.(cell).[(row * width) + column] = '#' then
             (Color.rgb 255 255 255, 255)
           else Image.clear)
     in
     Font.make ~fallback:'\127' ~atlas ~width ~height ~first ())
